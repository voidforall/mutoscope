// Vendors a curated set of Lucide icons (ISC) into the player as data:
// shape nodes rendered by React, never SVG markup. Run with the path of an
// extracted lucide-static package:
//   npm pack lucide-static@<version> && tar -xzf lucide-static-<version>.tgz
//   node scripts/vendor-icons.mjs package
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ICONS = `
user users users-round user-round bot brain handshake briefcase
server server-crash database database-zap cloud cloud-upload cloud-download hard-drive cpu network container cable plug
smartphone laptop monitor radio satellite wifi globe
file file-text folder archive inbox clipboard book book-open newspaper presentation quote
code terminal git-branch git-merge git-pull-request git-commit-horizontal package box layers workflow route milestone
lock lock-open key key-round shield shield-check fingerprint-pattern eye eye-off
zap gauge activity timer hourglass clock alarm-clock calendar calendar-check
mail message-square message-circle send share-2 bell bell-ring megaphone at-sign link
search settings cog sliders-horizontal funnel wrench hammer scissors pencil trash bug
circle-check circle-x triangle-alert octagon-alert circle-alert info circle-question-mark badge-check
trending-up trending-down chart-bar chart-column chart-line chart-pie sigma percent hash calculator infinity
dollar-sign credit-card wallet piggy-bank receipt shopping-cart store warehouse truck
map map-pin house building factory landmark
sun moon flame droplet wind leaf thermometer battery
plane car train-front ship bike footprints
coffee pizza utensils stethoscope pill syringe dna microscope atom flask-conical
image video lightbulb lightbulb-off sparkles rocket flag target puzzle scale gavel
heart star thumbs-up thumbs-down award trophy medal crown gem
arrow-right arrow-left arrow-up arrow-down repeat refresh-cw rotate-ccw download upload
list list-checks table grid-3x3 layout-dashboard
`.split(/\s+/).filter(Boolean);

const dir = process.argv[2];
if (!dir) throw new Error("usage: node scripts/vendor-icons.mjs <extracted lucide-static package dir>");
const { version } = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
const nodes = JSON.parse(readFileSync(join(dir, "icon-nodes.json"), "utf8"));
const TAGS = new Set(["path", "circle", "ellipse", "line", "polyline", "polygon", "rect"]);
const ATTRS = new Set(["d", "cx", "cy", "r", "rx", "ry", "x", "y", "x1", "y1", "x2", "y2", "width", "height", "points", "fill"]);

const picked = {};
for (const name of ICONS) {
  const icon = nodes[name];
  if (!icon) throw new Error(`lucide-static ${version} has no icon '${name}'`);
  picked[name] = icon.map(([tag, attrs]) => {
    if (!TAGS.has(tag)) throw new Error(`${name}: unexpected <${tag}>`);
    for (const k of Object.keys(attrs)) if (!ATTRS.has(k)) throw new Error(`${name}: unexpected attribute ${k}`);
    return [tag, attrs];
  });
}

const header = `// Generated by scripts/vendor-icons.mjs from lucide-static ${version}. Do not edit.\n`;
// ISC asks for the notice in all copies: "/*!" survives minification into the player bundle.
const notice = `/*! @license Lucide icons ${version} — ISC License. Copyright (c) Lucide Icons and Contributors. Permission to use, copy, modify, and/or distribute this software for any purpose with or without fee is hereby granted, provided that the above copyright notice and this permission notice appear in all copies. Portions derived from Feather (MIT), Copyright (c) 2013-2023 Cole Bemis. */\n`;
writeFileSync(
  "src/schema/icon-names.ts",
  `${header}// Lucide icons (ISC License, https://lucide.dev); see THIRD_PARTY_NOTICES.md.\n\nexport const ICON_NAMES = ${JSON.stringify(ICONS, null, 0).replace(/","/g, '", "')} as const;\nexport type IconName = (typeof ICON_NAMES)[number];\n`,
);
writeFileSync(
  "src/player/icons/lucide.ts",
  `${header}${notice}import type { IconName } from "../../schema";\n\nexport type IconNode = readonly [string, Readonly<Record<string, string>>];\n\nexport const LUCIDE: Readonly<Record<IconName, readonly IconNode[]>> = ${JSON.stringify(picked)};\n`,
);
writeFileSync(
  "skills/mutoscope/references/icons.md",
  "# Icons\n\nNames for `icon` entities, a component's `icon` and a list item's `icon`: " +
    `${ICONS.length} [Lucide](https://lucide.dev) icons (ISC License), bundled with the player. Validate rejects any other name.\n\n` +
    ICONS.map((n) => "`" + n + "`").join(" · ") +
    "\n",
);
console.log(`vendored ${ICONS.length} icons from lucide-static ${version}`);
