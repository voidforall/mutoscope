// Regenerates src/core/font-metrics.ts from the fonts bundled into the player:
// per-character advances that let validate predict wrapping exactly as the
// browser will. Run after changing fonts.css: npm run build && node scripts/measure-fonts.mjs
import { chromium } from "@playwright/test";
import { execFileSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const site = mkdtempSync(join(tmpdir(), "mutoscope-fonts-"));
execFileSync(process.execPath, ["skills/mutoscope/runtime/cli.mjs", "build", "examples/spsc-evolution", "--out", site]);
const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto(pathToFileURL(join(site, "index.html")).href);
await page.waitForFunction(() => window.mutoscope?.ready);
const fonts = { INTER_SEMIBOLD: "650 100px Inter", INTER_BOLD: "750 100px Inter", INTER_REGULAR: "400 100px Inter", SERIF_ITALIC: 'italic 400 100px "Source Serif 4"' };
const measured = await page.evaluate(async (fonts) => {
  const chars = [];
  for (let i = 32; i < 127; i++) chars.push(String.fromCharCode(i));
  chars.push("·", "–", "—", "…", "’", "“", "”", "→", "×", "≈");
  const ctx = document.createElement("canvas").getContext("2d");
  const out = {};
  for (const [name, font] of Object.entries(fonts)) {
    await document.fonts.load(font);
    ctx.font = font;
    out[name] = Object.fromEntries(chars.map((ch) => [ch, Math.round(ctx.measureText(ch).width) / 100]));
  }
  return out;
}, fonts);
await browser.close();
rmSync(site, { recursive: true, force: true });

const body = Object.entries(measured)
  .map(([name, table]) => `export const ${name}: Readonly<Record<string, number>> = ${JSON.stringify(table)};`)
  .join("\n\n");
writeFileSync(
  "src/core/font-metrics.ts",
  `// Generated by scripts/measure-fonts.mjs from the fonts in src/player/fonts.css. Do not edit.\n// Advance width of each character in em.\n\n${body}\n`,
);
console.log("wrote src/core/font-metrics.ts");
